// Regenerates src/data/imageSizes.js — the intrinsic [width, height] of every
// painting, so the gallery reserves each tile's space before the image loads
// (prevents the layout from shifting/jumping while images stream in).
//
// Run it whenever you add or rename images:   npm run sizes
// (macOS only — uses the built-in `sips` tool.)

import { readdirSync, writeFileSync } from 'fs';
import { execFileSync } from 'child_process';
import { fileURLToPath } from 'url';
import { dirname, join } from 'path';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SUB = '1. Paintings';
const DIR = join(ROOT, 'public/artwork', SUB);

const files = readdirSync(DIR)
  .filter((f) => /\.(jpe?g|png)$/i.test(f) && !f.startsWith('.'))
  .sort();

const paths = files.map((f) => join(DIR, f));
const out = execFileSync('sips', ['-g', 'pixelWidth', '-g', 'pixelHeight', ...paths], {
  encoding: 'utf8',
  maxBuffer: 64 * 1024 * 1024,
});

// Parse sips output into { absolutePath: {w, h} }
const dims = {};
let cur = null;
for (const line of out.split('\n')) {
  if (line.startsWith('/')) cur = line.trim();
  else if (line.includes('pixelWidth')) (dims[cur] ??= {}).w = parseInt(line.split(':')[1], 10);
  else if (line.includes('pixelHeight')) (dims[cur] ??= {}).h = parseInt(line.split(':')[1], 10);
}

const result = {};
let missing = 0;
files.forEach((f, i) => {
  const d = dims[paths[i]];
  if (d?.w && d?.h) result[`${SUB}/${f}`] = [d.w, d.h];
  else missing++;
});

const js =
  '// AUTO-GENERATED by `npm run sizes` — do not edit by hand.\n' +
  '// Intrinsic pixel size [width, height] per image, so the gallery can\n' +
  '// reserve space before an image loads (prevents layout shift/jumping).\n\n' +
  'export const imageSizes = ' + JSON.stringify(result, null, 0) + ';\n';

writeFileSync(join(ROOT, 'src/data/imageSizes.js'), js);
console.log(`wrote ${Object.keys(result).length} sizes${missing ? `, ${missing} missing` : ''}`);
